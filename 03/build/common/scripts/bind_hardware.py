"""Bind the actual local hardware sources, PS recipe and memory map; no EDA."""
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parents[1]
# User-required100MHz compute target; achieved timing remains a separate gate.
COMPUTE_HZ=100000000
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def read(p):return json.loads(p.read_text(encoding='utf-8-sig'))
def main():
    interface=(ROOT/'hardware/rtl/snapshot_compute_bdif.sv').read_text()
    assert f'ASSOCIATED_RESET resetn, FREQ_HZ {COMPUTE_HZ}"' in interface, 'Compute clock interface metadata disagrees with selected frequency'
    files=read(ROOT/'hardware/sources.json')['synthesis']
    files+=['hardware/sources.json','hardware/platform.tcl','config/ps_ethernet_candidate.json','firmware/memory_layout.h','scripts/bind_hardware.py']
    sources={p:sha(ROOT/p) for p in sorted(files)}
    digest=hashlib.sha256(json.dumps(sources,sort_keys=True).encode()).hexdigest()
    build=int(digest[:8],16) or 1
    addresses={'compute/S_AXI':'0x43c00000','compute/SGM_AXI':'0x43c30000','sensor/S_AXI':'0x43c10000','capture_ddr/S_AXI':'0x43c40000'}
    ports='pclk0 1 I pclk1 1 I vs0 1 I vs1 1 I href0 1 I href1 1 I data0 8 I data1 8 I scl0 1 I sda0 1 I scl1 1 I sda1 1 I camera_reset_level 1 I camera_pwdn_level 1 I camera_xclk_level 1 I scl0_low 1 O sda0_low 1 O scl1_low 1 O sda1_low 1 O camera_reset_low 1 O camera_pwdn_low 1 O'
    ps=read(ROOT/'config/ps_ethernet_candidate.json')['properties']
    t=['# Generated by scripts/bind_hardware.py; source identity, not a physical PASS.',f'set snapshot_build 0x{build:08x}',
       f'set snapshot_compute_hz {COMPUTE_HZ}',
       'set snapshot_rtl [list \\']
    for p in read(ROOT/'hardware/sources.json')['synthesis']:t.append(' [file join $root {'+p+'}] \\')
    t+= [']','set snapshot_ps [list \\']
    for k,v in ps.items():
        if any(c in k+v for c in '{}\\\n'):raise ValueError('Unexpected Tcl property character')
        t.append(' {'+k+'} {'+v+'} \\')
    t+= [']','set snapshot_addresses {'+' '.join(k+' '+v for k,v in addresses.items())+'}', 'set snapshot_camera_ports {'+ports+'}']
    (ROOT/'hardware/generated_contract.tcl').write_text('\n'.join(t)+'\n',encoding='utf-8')
    report={'status':'SOURCE_BOUND_NOT_GENERATED','source_digest':digest,'platform_id':f'0x{build:08x}','sgm_build':f'0x{build:08x}',
      'nn_base':addresses['compute/S_AXI'],'box_base':'0x43c00c00','sgm_base':addresses['compute/SGM_AXI'],
      'sensor_base':addresses['sensor/S_AXI'],'camera_base':addresses['capture_ddr/S_AXI'],
      'dma_window':['0x10000000','0x1c000000'],'sgm_software_window':['0x194e0000','0x19666000'],'compute_software_window':['0x19000000','0x1a000000'],'backend':'v351a_v279_FIELD_PS',
      'clock_hz':{'board':50000000,'compute_conditional':COMPUTE_HZ},'ps_ddr_bytes':1073741824,
      'sources':sources,'generated_tcl_sha256':sha(ROOT/'hardware/generated_contract.tcl'),
      'pending':['actual BD/IP validation and generated PS init/FSBL binding','source-bound complete numerical and resource gates','camera pins and real source-synchronous timing/CDC evidence','real physical and board acceptance'],
      'physical_pass':False,'board_operations':0}
    (ROOT/'hardware/contract.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({'build':report['platform_id'],'source_files':len(sources),'status':report['status']}))
if __name__=='__main__':main()
