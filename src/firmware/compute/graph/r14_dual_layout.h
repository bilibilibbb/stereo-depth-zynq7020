#ifndef R14_DUAL_LAYOUT_H
#define R14_DUAL_LAYOUT_H
#include <stdint.h>
/* New software-integration map. Existing released images are unchanged.
 * Every range is half-open, cache-line aligned, in the existing DMA window.
 * SGM four-field packing retains all original byte counts and geometry. */
#define R14_DUAL_DMA_BEGIN 0x19000000u
#define R14_DUAL_DMA_END 0x1a000000u
#define R14_DUAL_TENSOR_BYTES 2457600u
#define R14_DUAL_TENSOR0 0x19000000u
#define R14_DUAL_TENSOR1 0x19260000u
#define R14_DUAL_WEIGHTS 0x194c0000u
#define R14_DUAL_WEIGHT_BYTES 65536u
#define R14_DUAL_SGM0 0x194e0000u
#define R14_DUAL_SGM1 0x19680000u
#define R14_DUAL_CENSUS_BYTES 307200u
#define R14_DUAL_CURVE_BYTES 368640u
#define R14_DUAL_NATIVE_BYTES 614400u
#define R14_DUAL_SGM_RIGHT_OFFSET 0x4b000u
#define R14_DUAL_SGM_CURVE_OFFSET 0x96000u
#define R14_DUAL_SGM_NATIVE_OFFSET 0xf0000u
#define R14_DUAL_SGM_BYTES 0x186000u
#define R14_DUAL_MEDIAN_BYTES 307200u
#define R14_DUAL_MEDIAN_SOURCE0 0x19810000u
#define R14_DUAL_MEDIAN_DEST0 0x19860000u
#define R14_DUAL_MEDIAN_SOURCE1 0x198b0000u
#define R14_DUAL_MEDIAN_DEST1 0x19900000u
#define R14_DUAL_FP_WORK_BEGIN 0x19950000u
#define R14_DUAL_FP_WORK_BYTES (R14_DUAL_DMA_END-R14_DUAL_FP_WORK_BEGIN)
typedef struct {uint32_t address,bytes;} r14_region;
static const r14_region r14_dual_regions[]={
 {R14_DUAL_TENSOR0,R14_DUAL_TENSOR_BYTES},{R14_DUAL_TENSOR1,R14_DUAL_TENSOR_BYTES},
 {R14_DUAL_WEIGHTS,R14_DUAL_WEIGHT_BYTES},
 {R14_DUAL_SGM0,R14_DUAL_CENSUS_BYTES},{R14_DUAL_SGM0+R14_DUAL_SGM_RIGHT_OFFSET,R14_DUAL_CENSUS_BYTES},
 {R14_DUAL_SGM0+R14_DUAL_SGM_CURVE_OFFSET,R14_DUAL_CURVE_BYTES},{R14_DUAL_SGM0+R14_DUAL_SGM_NATIVE_OFFSET,R14_DUAL_NATIVE_BYTES},
 {R14_DUAL_SGM1,R14_DUAL_CENSUS_BYTES},{R14_DUAL_SGM1+R14_DUAL_SGM_RIGHT_OFFSET,R14_DUAL_CENSUS_BYTES},
 {R14_DUAL_SGM1+R14_DUAL_SGM_CURVE_OFFSET,R14_DUAL_CURVE_BYTES},{R14_DUAL_SGM1+R14_DUAL_SGM_NATIVE_OFFSET,R14_DUAL_NATIVE_BYTES},
 {R14_DUAL_MEDIAN_SOURCE0,R14_DUAL_MEDIAN_BYTES},{R14_DUAL_MEDIAN_DEST0,R14_DUAL_MEDIAN_BYTES},
 {R14_DUAL_MEDIAN_SOURCE1,R14_DUAL_MEDIAN_BYTES},{R14_DUAL_MEDIAN_DEST1,R14_DUAL_MEDIAN_BYTES},
 {R14_DUAL_FP_WORK_BEGIN,R14_DUAL_FP_WORK_BYTES}
};
int r14_dual_layout_valid(void);
#endif
